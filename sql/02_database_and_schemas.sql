-- =====================================================================
-- 02: database, schemas, grants
-- Run as SYSADMIN (it owns the objects, so it can grant on them).
-- =====================================================================
USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS F1_DWH;

CREATE SCHEMA IF NOT EXISTS F1_DWH.RAW;
CREATE SCHEMA IF NOT EXISTS F1_DWH.STAGING;
CREATE SCHEMA IF NOT EXISTS F1_DWH.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS F1_DWH.MARTS;
CREATE SCHEMA IF NOT EXISTS F1_DWH.SNAPSHOTS;


-- ---- Database access ----
GRANT USAGE ON DATABASE F1_DWH TO ROLE F1_LOADER;
GRANT USAGE ON DATABASE F1_DWH TO ROLE F1_TRANSFORMER;
GRANT USAGE ON DATABASE F1_DWH TO ROLE F1_REPORTER;

-- ---- F1_LOADER: owns what it creates in RAW ----
GRANT USAGE ON SCHEMA F1_DWH.RAW TO ROLE F1_LOADER;
GRANT CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT
    ON SCHEMA F1_DWH.RAW TO ROLE F1_LOADER;

-- ---- F1_TRANSFORMER: reads RAW, full control of everything else ----
GRANT USAGE ON SCHEMA F1_DWH.RAW TO ROLE F1_TRANSFORMER;
GRANT SELECT ON ALL TABLES    IN SCHEMA F1_DWH.RAW TO ROLE F1_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA F1_DWH.RAW TO ROLE F1_TRANSFORMER;

GRANT ALL PRIVILEGES ON SCHEMA F1_DWH.STAGING      TO ROLE F1_TRANSFORMER;
GRANT ALL PRIVILEGES ON SCHEMA F1_DWH.INTERMEDIATE TO ROLE F1_TRANSFORMER;
GRANT ALL PRIVILEGES ON SCHEMA F1_DWH.MARTS        TO ROLE F1_TRANSFORMER;
GRANT ALL PRIVILEGES ON SCHEMA F1_DWH.SNAPSHOTS    TO ROLE F1_TRANSFORMER;

-- ---- F1_REPORTER: read-only on MARTS ----
GRANT USAGE ON SCHEMA F1_DWH.MARTS TO ROLE F1_REPORTER;
GRANT SELECT ON ALL TABLES     IN SCHEMA F1_DWH.MARTS TO ROLE F1_REPORTER;
GRANT SELECT ON FUTURE TABLES  IN SCHEMA F1_DWH.MARTS TO ROLE F1_REPORTER;
GRANT SELECT ON ALL VIEWS      IN SCHEMA F1_DWH.MARTS TO ROLE F1_REPORTER;
GRANT SELECT ON FUTURE VIEWS   IN SCHEMA F1_DWH.MARTS TO ROLE F1_REPORTER;
