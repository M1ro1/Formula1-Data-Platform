-- =====================================================================
-- 03: RAW layer - file format, internal stage, one table per API entity
-- Run as F1_LOADER (it will own these objects).
-- Every table keeps the API response untouched in PAYLOAD plus load metadata.
-- =====================================================================
USE ROLE F1_LOADER;
USE WAREHOUSE F1_WH;
USE SCHEMA F1_DWH.RAW;

CREATE FILE FORMAT IF NOT EXISTS FF_JSON
TYPE = JSON
STRIP_OUTER_ARRAY = FALSE;

-- Internal stage: Airflow uploads JSON files here with PUT,
-- then COPY INTO the tables
CREATE STAGE IF NOT EXISTS STG_F1_RAW
    FILE_FORMAT = FF_JSON
    COMMENT = 'Landing zone for raw Jolpica-F1 API responses';

-- SEASON / ROUND are the request parameters (NULL where not applicable)
CREATE TABLE IF NOT EXISTS RAW_SEASONS (
    PAYLOAD VARIANT,
    SEASON NUMBER(4, 0),
    ROUND NUMBER(3, 0),
    _SOURCE_FILE STRING,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RAW_DRIVERS (
    PAYLOAD VARIANT,
    SEASON NUMBER(4, 0),
    ROUND NUMBER(3, 0),
    _SOURCE_FILE STRING,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

